def test_engine_change_retained_as_failure(inputs, monkeypatch):
    config, path, _ = inputs
    source = path.parent / "0.png"
    original_bytes = source.read_bytes()
    source.write_bytes(b"broken")
    failed = dataset_import.begin(config, path)
    source.write_bytes(original_bytes)
    original = dataset_import._worker

    def changed(python, arguments):
        value = original(python, arguments)
        if arguments == ["--probe"]:
            value["python"] = "changed"
        return value

    monkeypatch.setattr(dataset_import, "_worker", changed)
    result = dataset_import.recover(config, Path(failed["artifacts"]["operation"]))
    assert result["failure_boundary"] == "engine" and result["status"] == "failed"


def test_source_directory_redirect_refused(inputs, tmp_path):
    config, path, value = inputs
    redirected = path.parent / "linked"
    if os.name == "nt":
        # Native junctions do not require symlink privileges.
        result = subprocess.run(
            ["cmd", "/c", "mklink", "/J", str(redirected), str(tmp_path)], capture_output=True
        )
        assert result.returncode == 0, result.stderr
    else:
        redirected.symlink_to(tmp_path, target_is_directory=True)
    try:
        value["samples"][0]["source"]["path"] = "linked/inputs/0.png"
        document(path, value)
        result = dataset_import.begin(config, path)
        assert result["status"] == "failed" and "redirect" in result["error"]
    finally:
        redirected.rmdir() if os.name == "nt" else redirected.unlink()


