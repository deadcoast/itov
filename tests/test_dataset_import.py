@pytest.mark.parametrize("kind", ["jpeg", "jpeg_truncated", "cmyk", "pixel_limit"])
def test_decode_jpeg_and_image_bounds(inputs, kind):
    import struct
    import zlib

    config, path, value = inputs
    source = path.parent / "0.png"
    if kind == "pixel_limit":
        raw = source.read_bytes()
        header = struct.pack(">IIBBBBB", 8001, 4000, 8, 2, 0, 0, 0)
        source.write_bytes(
            raw[:16] + header + struct.pack(">I", zlib.crc32(b"IHDR" + header)) + raw[33:]
        )
    else:
        Image.new("CMYK" if kind == "cmyk" else "RGB", (91, 47)).save(source, format="JPEG")
        if kind == "jpeg_truncated":
            source.write_bytes(source.read_bytes()[:-30])
    value["samples"][0]["source"]["sha256"] = sha256(source.read_bytes())
    document(path, value)
    result = dataset_import.begin(config, path)
    assert result["status"] == ("committed" if kind == "jpeg" else "failed")
    if kind != "jpeg":
        assert result["failure_boundary"] == "decode_transform"


def test_destination_conflict_never_overwrites_unrelated_bytes(inputs, monkeypatch):
    config, path, _ = inputs
    original = dataset_import._publish_bundle

    def conflict(payload, final, import_id):
        final.mkdir(parents=True)
        (final / "unrelated.txt").write_bytes(b"preserve me")
        original(payload, final, import_id)

    monkeypatch.setattr(dataset_import, "_publish_bundle", conflict)
    result = dataset_import.begin(config, path)
    assert result["status"] == "artifact_invalid"
    final = config.root / dataset_snapshot.prefix(result["import_id"])
    assert files(final) == {"unrelated.txt": sha256(b"preserve me")}
    attempt = Path(result["artifacts"]["attempt record"]).parent
    assert json.loads((attempt / "attempt.json").read_bytes())["failure_boundary"] == "publication"
    assert (attempt / "payload/READY.json").is_file()


