def declare(folder, *, met=False):
    folder.mkdir(parents=True, exist_ok=True)
    samples = []
    for n in range(2):
        path = folder / f"{n}.png"
        image = Image.new("RGB" if n == 0 else "L", (80, 40), (160, 20, 30) if n == 0 else 90)
        exif = Image.Exif()
        exif[274] = 6 if n == 0 else 1
        image.save(path, exif=exif)
        provenance = {"selection_note": "Fixture geometry", "caption_note": "Fixture caption"}
        if met:
            url = f"https://images.metmuseum.org/CRDImages/test/{n}.jpg"
            metadata = {
                "objectID": n + 1,
                "isPublicDomain": True,
                "primaryImageSmall": url,
                "artistDisplayName": f"Fixture Artist {n}",
            }
            provenance.update(
                object_id=n + 1,
                image_url=url,
                metadata=write(folder, f"{n}.json", canonical_bytes(metadata)),
            )
        else:
            provenance["reference"] = "Generated by test_dataset_import.py"
        samples.append(
            {
                "id": f"sample-{n}",
                "split": "train" if n == 0 else "validation",
                "group": f"met-{n + 1}" if met else f"fixture-{n}",
                "source": {"path": path.name, "sha256": sha256(path.read_bytes())},
                "caption": write(folder, f"{n}.txt", b"testtrigger rectangle\r\n"),
                "provenance": provenance,
            }
        )
    value = {
        "version": 1,
        "id": "fixture",
        "provider": "met-open-access" if met else "local",
        "purpose": "training" if met else "smoke",
        "origin": {"title": "Import fixture", "reference": "test_dataset_import.py"},
        "rights": {
            "basis": "Generated fixture",
            "reference": "test_dataset_import.py",
            "training_permitted": True,
        },
        "transform": curation.TRANSFORM,
        "curation": None,
        "samples": samples,
    }
    if met:
        value["curation"] = {
            "curator": "Test",
            "selection_policy": "Fixture only",
            "policy_url": curation.POLICY,
            "policy_snapshot": write(folder, "policy.json", b'{"fixture":true}'),
        }
    return document(folder / "import.json", value), value


